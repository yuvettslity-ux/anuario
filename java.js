const book = document.getElementById('book'), lbl = document.getElementById('lbl'), mq = matchMedia('(max-width:820px)');
const N = pages.length;
let per = 2, L = 0, cur = 0, leaves = [];
const max = () => per === 2 ? L : L - 1;

function build() {
  const page = cur * per;
  per = mq.matches ? 1 : 2;
  L = Math.ceil(N / per);
  cur = Math.min(Math.floor(page / per), max());
  book.innerHTML = ''; leaves = [];
  const face = (k, c) => k < N ? `<div class="face ${c} ${per === 2 ? (k % 2 ? 'l' : 'r') : ''}">${pages[k]}${k && k < N - 1 ? `<span class="num">${k}</span>` : ''}</div>` : '';
  for (let i = 0; i < L; i++) {
    const el = document.createElement('div');
    el.className = 'leaf';
    el.innerHTML = face(i * per, 'f') + (per === 2 ? face(i * per + 1, 'b') : '');
    book.append(el); leaves.push(el);
  }
  paint(cur, true);
}

function paint(old, now) {
  if (now) book.classList.add('snap');
  leaves.forEach((el, i) => {
    const on = i < cur;
    if (!now && on === el.classList.contains('on')) return;
    const step = on ? i - old : old - 1 - i;
    el.style.transitionDelay = (now ? 0 : Math.min(step, 12) * 80) + 'ms';
    el.style.zIndex = L + 5;
    el.classList.toggle('on', on);
    setTimeout(() => el.style.zIndex = on ? i : L - i, now ? 0 : Math.min(step, 12) * 80 + 450);
  });
  book.classList.toggle('first', per === 2 && cur === 0);
  book.classList.toggle('last', per === 2 && cur === L);
  lbl.textContent = cur === 0 ? 'Portada'
    : per === 2 ? (cur === L ? 'Contraportada' : `Págs. ${cur * 2 - 1}–${cur * 2}`)
    : (cur === L - 1 ? 'Contraportada' : `Pág. ${cur}`);
  if (now) requestAnimationFrame(() => requestAnimationFrame(() => book.classList.remove('snap')));
}

function go(n) {
  n = Math.max(0, Math.min(max(), n));
  if (n === cur) return;
  const old = cur; cur = n; paint(old);
}
